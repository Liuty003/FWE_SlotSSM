#!/usr/bin/env python3
"""Replay successful anchor-FSM teachers while recording neural BC inputs.

The reference reports were generated by a teacher controller that has offline
target/placement anchors.  This collector uses those anchors *only* to replay
the already verified teacher and write its actions as labels.  Every saved
row, and the eventual neural policy trained from it, uses RGB, wrist RGB,
language, robot proprio and executed-action history exclusively.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_BASE = Path("/data2/lty/naive-e-slotssm-runs/oft-plus-book-local-repair-v1")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--reference-root", type=Path,
                        default=DEFAULT_BASE / "candidate-fsm-online-v2-sharedvision")
    parser.add_argument("--output-root", type=Path, required=True)
    parser.add_argument("--task-ids", type=int, nargs="+", required=True)
    parser.add_argument("--gpu", type=int, required=True)
    parser.add_argument("--base", type=Path, default=DEFAULT_BASE)
    parser.add_argument("--max-policy-steps", type=int)
    return parser.parse_args()


def csv(values: list[float]) -> str:
    return ",".join(str(float(value)) for value in values)


def first_recovery(report: dict) -> dict:
    for row in report["decisions"]:
        if row["mode"] == "RECOVERY":
            required = ("task_specific_target_anchor", "task_specific_placement_anchor", "geometry_xy_offset")
            if any(row.get(key) is None for key in required):
                raise ValueError(f"reference recovery is missing anchor data: {required}")
            return row
    raise RuntimeError("reference rollout never entered recovery")


def main() -> None:
    args = parse_args()
    python = ROOT / ".conda/envs/openvla-oft/bin/python"
    runner = ROOT / "scripts/run_oft_slotssm_unified_episode.py"
    if not python.is_file() or not runner.is_file():
        raise FileNotFoundError("missing OFT runtime or unified runner")
    args.output_root.mkdir(parents=True, exist_ok=True)
    for task_id in args.task_ids:
        reference_path = args.reference_root / f"task{task_id}" / f"task{task_id}-episode0.json"
        report = json.loads(reference_path.read_text(encoding="utf-8"))
        if not report.get("success"):
            print(json.dumps({"task_id": task_id, "skipped": "reference teacher failed"}), flush=True)
            continue
        teacher = first_recovery(report)
        target = csv(teacher["task_specific_target_anchor"])
        placement = csv(teacher["task_specific_placement_anchor"])
        offset = csv(teacher["geometry_xy_offset"])
        command = [
            str(python), str(runner), "--gpu", str(args.gpu),
            "--task-suite", "libero_10", "--task-id", str(task_id), "--episode-id", "0",
            "--official-normal-actions", "--normal-open-loop", "8",
            "--max-learned-recoveries", "1", "--learned-recovery-max-steps", "70",
            "--recovery-confirm-steps", "2",
            "--adapter-checkpoint", str(args.base / "neural-geometry-v8-aux/recovery-head-v8/adapter_best.safetensors"),
            "--gate-checkpoint", str(args.base / "gate-v7-dense-trigger-20260809/gate_best.safetensors"),
            "--gate-num-classes", "2",
            # During data collection, the archived intervention timestep is
            # the sole teacher trigger.  Suppress a differently calibrated
            # current gate before that point; otherwise it can enter an
            # off-policy recovery state (notably 504/511/512/513) before the
            # verified teacher action sequence begins.
            "--recovery-probability-threshold", "1.0",
            "--recovery-geometry-controller", "--recovery-anchor-fsm",
            # Coordinates can begin with a minus sign.  ``argparse`` treats
            # a separate negative token as another option, hence ``=``.
            f"--recovery-target-anchor={target}",
            f"--recovery-placement-anchor={placement}",
            f"--recovery-geometry-xy-offset={offset}",
            # The archived teacher was produced with an earlier gate whose
            # score calibration is not reproducible bit-for-bit with the
            # current v7 deployment gate.  Its reported intervention point
            # is an offline teacher label, so replay it as a forced *teacher*
            # window.  This guarantees that the saved action labels start
            # from the verified source state; the eventual neural policy is
            # never given this step index or an oracle trigger.
            "--force-recovery-at-step", str(int(teacher["step"])),
            "--force-recovery-steps", "70",
            "--save-online-images", "--output-dir", str(args.output_root / f"task{task_id}"),
        ]
        if teacher.get("task_specific_placement_quat") is not None:
            command.append(f"--recovery-placement-quat={csv(teacher['task_specific_placement_quat'])}")
        if args.max_policy_steps is not None:
            command.extend(["--max-policy-steps", str(args.max_policy_steps)])
        environment = os.environ.copy()
        environment.update({"CUDA_VISIBLE_DEVICES": str(args.gpu), "MUJOCO_GL": "egl",
                            "PYOPENGL_PLATFORM": "egl", "TOKENIZERS_PARALLELISM": "false"})
        print(json.dumps({"task_id": task_id, "reference_recovery_step": teacher["step"],
                          "target_anchor": target, "placement_anchor": placement, "offset": offset}), flush=True)
        subprocess.run(command, cwd=ROOT, env=environment, check=True)
        output_report = args.output_root / f"task{task_id}" / f"task{task_id}-episode0.json"
        replay = json.loads(output_report.read_text(encoding="utf-8"))
        replay_recovery = next((row for row in replay["decisions"] if row.get("mode") == "RECOVERY"), None)
        if replay_recovery is None:
            raise RuntimeError(f"teacher replay never entered recovery: task {task_id}")
        if (int(replay_recovery["step"]) != int(teacher["step"]) or
                not bool(replay_recovery.get("forced_recovery"))):
            raise RuntimeError(
                f"teacher replay trigger drift for task {task_id}: "
                f"expected forced step {teacher['step']}, got {replay_recovery['step']}"
            )
        if not replay.get("success"):
            raise RuntimeError(f"teacher replay failed task {task_id}")


if __name__ == "__main__":
    main()
